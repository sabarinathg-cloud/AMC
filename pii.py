def detect_pii_piiranha(text, threshold=0.45):
    if piiranha_pipe is None:
        return []

    text = str(text)
    raw = piiranha_pipe(text)

    entities = []
    for e in raw:
        raw_label = str(e.get("entity_group", e.get("entity", ""))).upper()
        score = float(e.get("score", 0.0))

        if score < threshold:
            continue
        if raw_label not in PIIRANHA_LABEL_MAP:
            continue

        start = int(e.get("start", -1))
        end = int(e.get("end", -1))
        if start < 0 or end <= start:
            continue

        entities.append({
            "text": text[start:end],
            "label": PIIRANHA_LABEL_MAP[raw_label],
            "start": start,
            "end": end,
            "score": score,
            "source": "piiranha",
            "raw_label": raw_label,
        })

    return resolve_overlaps(entities)


