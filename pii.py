def build_token_alignment(transcript_text, word_df):
    """
    Map transcript tokens to aligned word rows using normalized token sequence.
    """
    txt_tokens = transcript_tokens_with_spans(transcript_text)
    txt_norms = [t["norm"] for t in txt_tokens if t["norm"]]

    wd = word_df.copy()
    wd["norm"] = wd["word"].astype(str).map(normalize_token)
    wd = wd[wd["norm"] != ""].reset_index(drop=False)  # keep original row index

    word_norms = wd["norm"].tolist()

    # map transcript token index -> row index in word_df
    mapping = [None] * len(txt_tokens)

    txt_nonempty_positions = [i for i, t in enumerate(txt_tokens) if t["norm"]]
    sm = SequenceMatcher(None, txt_norms, word_norms)

    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            for a, b in zip(range(i1, i2), range(j1, j2)):
                mapping[txt_nonempty_positions[a]] = int(wd.iloc[b]["index"])
        elif tag == "replace":
            shared = min(i2 - i1, j2 - j1)
            for k in range(shared):
                mapping[txt_nonempty_positions[i1 + k]] = int(wd.iloc[j1 + k]["index"])

    return txt_tokens, mapping


def entities_to_time_ranges(entities, transcript_text, word_df, pad_sec=0.06):
    txt_tokens, mapping = build_token_alignment(transcript_text, word_df)

    rows = []
    for ent in entities:
        covered_token_idx = []
        for i, tok in enumerate(txt_tokens):
            overlap = not (tok["end_char"] <= ent["start"] or tok["start_char"] >= ent["end"])
            if overlap and mapping[i] is not None:
                covered_token_idx.append(mapping[i])

        if not covered_token_idx:
            continue

        sub = word_df.loc[sorted(set(covered_token_idx))]
        start = max(0.0, float(sub["start"].min()) - pad_sec)
        end = float(sub["end"].max()) + pad_sec

        rows.append({
            "text": ent["text"],
            "type": ent["type"],
            "source": ent["source"],
            "start": start,
            "end": end,
            "duration": end - start,
        })

    if not rows:
        return pd.DataFrame(columns=["text", "type", "source", "start", "end", "duration"])

    time_df = pd.DataFrame(rows).sort_values(["start", "end"]).reset_index(drop=True)
    return time_df


def merge_time_ranges(time_df):
    if time_df.empty:
        return time_df.copy()

    merged = []
    cur = time_df.iloc[0].to_dict()

    for _, row in time_df.iloc[1:].iterrows():
        if float(row["start"]) <= float(cur["end"]):
            cur["end"] = max(float(cur["end"]), float(row["end"]))
            cur["duration"] = float(cur["end"]) - float(cur["start"])
            cur["text"] = cur["text"] + " | " + row["text"]
            cur["type"] = cur["type"] + " | " + row["type"]
            cur["source"] = cur["source"] + " | " + row["source"]
        else:
            merged.append(cur)
            cur = row.to_dict()

    merged.append(cur)
    return pd.DataFrame(merged)


