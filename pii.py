def resolve_overlaps(entities):
    entities = sorted(
        entities,
        key=lambda x: (x["start"], -(x["end"] - x["start"]), -x["score"])
    )

    kept = []
    for ent in entities:
        has_overlap = False
        replace_idx = None

        for i, k in enumerate(kept):
            overlap = not (ent["end"] <= k["start"] or ent["start"] >= k["end"])
            if overlap:
                has_overlap = True
                if ent["score"] > k["score"]:
                    replace_idx = i
                break

        if not has_overlap:
            kept.append(ent)
        elif replace_idx is not None:
            kept[replace_idx] = ent

    kept = sorted(kept, key=lambda x: x["start"])
    return kept


