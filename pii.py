def resolve_overlaps(entities):
    entities = sorted(
        entities,
        key=lambda x: (x["start"], -(x["end"] - x["start"]), -x["score"])
    )

    kept = []
    for ent in entities:
        overlapping_indices = []

        for i, k in enumerate(kept):
            overlap = not (ent["end"] <= k["start"] or ent["start"] >= k["end"])
            if overlap:
                overlapping_indices.append(i)

        if not overlapping_indices:
            kept.append(ent)
            continue

        # Keep highest score entity among overlapping ones
        best = ent
        replace_indices = []
        for i in overlapping_indices:
            if kept[i]["score"] > best["score"]:
                best = kept[i]
            replace_indices.append(i)

        for i in sorted(replace_indices, reverse=True):
            kept.pop(i)

        kept.append(best)

    kept = sorted(kept, key=lambda x: x["start"])
    return kept

