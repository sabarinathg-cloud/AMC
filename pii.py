def apply_beep_mask(audio, sr, spans, beep_freq=1000.0, beep_gain=0.25, fade_ms=8):
    x = np.array(audio, dtype=np.float32, copy=True)
    mono = False

    if x.ndim == 1:
        x = x[:, None]
        mono = True

    n_channels = x.shape[1]
    fade = max(1, int(sr * fade_ms / 1000))

    peak = np.max(np.abs(x)) if np.max(np.abs(x)) > 0 else 1.0
    amp = beep_gain * peak

    for _, r in spans.iterrows():
        s = max(0, int(float(r["start"]) * sr))
        e = min(len(x), int(float(r["end"]) * sr))
        if e <= s:
            continue

        n = e - s
        t = np.arange(n) / sr
        tone = amp * np.sin(2 * np.pi * beep_freq * t)

        if n > 2 * fade:
            env = np.ones(n, dtype=np.float32)
            env[:fade] = np.linspace(0, 1, fade)
            env[-fade:] = np.linspace(1, 0, fade)
            tone = tone * env

        tone = np.tile(tone[:, None], (1, n_channels))
        x[s:e, :] = tone

    if mono:
        x = x[:, 0]
    return x


def apply_silence_mask(audio, sr, spans):
    x = np.array(audio, dtype=np.float32, copy=True)
    for _, r in spans.iterrows():
        s = max(0, int(float(r["start"]) * sr))
        e = min(len(x), int(float(r["end"]) * sr))
        if e > s:
            x[s:e] = 0
    return x


