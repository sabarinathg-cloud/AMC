def transcript_tokens_with_spans(text):
    """
    Tokenize transcript while keeping character spans.
    """
    text = str(text)
    pattern = re.compile(r"[A-Za-z0-9@._%+\-']+")
    rows = []
    for m in pattern.finditer(text):
        token = m.group(0)
        rows.append({
            "text": token,
            "start_char": m.start(),
            "end_char": m.end(),
            "norm": normalize_token(token),
        })
    return rows


