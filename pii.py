def likely_person_name(span_text):
    toks = str(span_text).strip().lower().split()

    if not toks or len(toks) > 3:
        return False
    if any(len(t) < 2 for t in toks):
        return False
    if any(t in NAME_BLACKLIST for t in toks):
        return False
    return True


def detect_rule_person_names(text):
    text = str(text)
