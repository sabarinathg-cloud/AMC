# Regex + saved-json PII detection
# -----------------------------------------------------------------------------
EMAIL_RE = re.compile(r"\b[a-zA-Z0-9._%+\-]+@[a-zA-Z0-9.\-]+\.[A-Za-z]{2,}\b")
PHONE_RE = re.compile(r"(?<!\d)(?:\+?1[-.\s]?)?(?:\(?\d{3}\)?[-.\s]?)?\d{3}[-.\s]?\d{4}(?!\d)")
SSN_RE = re.compile(r"\b\d{3}-\d{2}-\d{4}\b")
DOB_RE = re.compile(r"\b(?:0?[1-9]|1[0-2])[/-](?:0?[1-9]|[12]\d|3[01])[/-](?:\d{2}|\d{4})\b")
ZIP_RE = re.compile(r"\b\d{5}(?:-\d{4})?\b")

ID_CONTEXT_RE = re.compile(
    r"\b(?:member|account|policy|reference|case|claim|mrn|subscriber|insurance)\s*"
    r"(?:number|no\.?|#|id)?\s*[:\-]?\s*([A-Z0-9\-]{4,})\b",
    flags=re.IGNORECASE,
)

BAD_ID_WORDS = {
    "number", "member", "account", "policy", "reference", "case",
    "claim", "subscriber", "insurance", "id", "no"
}


def is_valid_id_candidate(value):
    value = str(value).strip()
    norm = re.sub(r"[^A-Za-z0-9]", "", value).lower()

    if not norm:
        return False
    if norm in BAD_ID_WORDS:
        return False
    if norm.isalpha():
        return False
    if len(norm) < 4:
        return False
    return any(ch.isdigit() for ch in norm)


def detect_pii_regex(text):
    text = str(text)
    entities = []

    for m in EMAIL_RE.finditer(text):
        entities.append({"text": m.group(0), "type": "EMAIL", "start": m.start(), "end": m.end(), "source": "regex"})

    for m in PHONE_RE.finditer(text):
        entities.append({"text": m.group(0), "type": "PHONE", "start": m.start(), "end": m.end(), "source": "regex"})

    for m in SSN_RE.finditer(text):
        entities.append({"text": m.group(0), "type": "SSN", "start": m.start(), "end": m.end(), "source": "regex"})

    for m in DOB_RE.finditer(text):
        entities.append({"text": m.group(0), "type": "DOB", "start": m.start(), "end": m.end(), "source": "regex"})

    for m in ZIP_RE.finditer(text):
        entities.append({"text": m.group(0), "type": "ZIP", "start": m.start(), "end": m.end(), "source": "regex"})

    for m in ID_CONTEXT_RE.finditer(text):
        value = m.group(1)
        if not is_valid_id_candidate(value):
            continue

        entities.append({
            "text": value,
            "type": "ID",
            "start": m.start(1),
            "end": m.end(1),
            "source": "regex",
        })

    return entities


def detect_pii_from_saved_json(row, transcript):
    entities = []

    if "pii_phi_json" not in row or pd.isna(row["pii_phi_json"]) or not str(row["pii_phi_json"]).strip():
        return entities

    try:
        obj = json.loads(str(row["pii_phi_json"]))
    except Exception:
        return entities

    for ent in obj.get("entities", []):
        if not isinstance(ent, dict):
            continue
        if str(ent.get("category", "")).upper() != "PII":
            continue

        ent_text = str(ent.get("text", "")).strip()
        ent_type = str(ent.get("type", "PII")).strip().upper()

        if not ent_text:
            continue

        for m in re.finditer(re.escape(ent_text), transcript, flags=re.IGNORECASE):
            entities.append({
                "text": m.group(0),
                "type": ent_type,
                "start": m.start(),
                "end": m.end(),
                "source": "pii_phi_json",
            })

    return entities


