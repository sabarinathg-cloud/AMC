def entity_to_search_tokens(text):
    raw_tokens = re.findall(r"[A-Za-z0-9@._%+\-']+", str(text))
    out = []

    for tok in raw_tokens:
        norm = normalize_token(tok)
        if not norm:
            continue

        if norm.isdigit():
            out.extend(DIGIT_WORDS_LOWER[d] for d in norm)
        else:
            out.append(norm)

    return out


def entities_to_time_ranges(entities, word_df, pad_sec=0.08, min_duration=0.25):
    if word_df is None or not isinstance(word_df, pd.DataFrame) or word_df.empty:
        print("No aligned word timestamps available.")
        return pd.DataFrame(columns=["text", "type", "source", "start", "end", "duration"])

    required = ["word", "start", "end"]
    missing = [c for c in required if c not in word_df.columns]
    if missing:
        print("Alignment output is missing columns:", missing)
        print("Available columns:", list(word_df.columns))
        return pd.DataFrame(columns=["text", "type", "source", "start", "end", "duration"])

    wd = word_df.copy()
    wd["norm"] = wd["word"].astype(str).map(normalize_token)
    wd = wd[wd["norm"] != ""].reset_index(drop=True)

    if wd.empty:
        print("Aligned word timestamps exist but contain no usable words.")
        return pd.DataFrame(columns=["text", "type", "source", "start", "end", "duration"])

    word_norms = wd["norm"].tolist()
    rows = []

    for ent in entities:
        search_toks = entity_to_search_tokens(ent["text"])
        if not search_toks:
            continue

        found_any = False
        n = len(search_toks)

        for i in range(len(word_norms) - n + 1):
            if word_norms[i:i+n] == search_toks:
                start = max(0.0, float(wd.iloc[i]["start"]) - pad_sec)
                end = float(wd.iloc[i+n-1]["end"]) + pad_sec

                if end - start < min_duration:
                    mid = (start + end) / 2
                    start = max(0.0, mid - min_duration / 2)
                    end = mid + min_duration / 2

                rows.append({
                    "text": ent["text"],
                    "type": ent["type"],
                    "source": ent["source"],
                    "start": start,
                    "end": end,
                    "duration": end - start,
                })
                found_any = True

        if not found_any:
            print("Could not map entity to timestamps:", ent["text"], "| type:", ent["type"])

    if not rows:
        return pd.DataFrame(columns=["text", "type", "source", "start", "end", "duration"])

    return pd.DataFrame(rows).sort_values(["start", "end"]).reset_index(drop=True)


def merge_time_ranges(time_df):
    if time_df is None or time_df.empty:
        return pd.DataFrame(columns=["text", "type", "source", "start", "end", "duration"])

    merged = []
    cur = time_df.iloc[0].to_dict()

    for _, row in time_df.iloc[1:].iterrows():
        if float(row["start"]) <= float(cur["end"]):
            cur["end"] = max(float(cur["end"]), float(row["end"]))
            cur["duration"] = float(cur["end"]) - float(cur["start"])
        else:
            merged.append(cur)
            cur = row.to_dict()

    merged.append(cur)
    return pd.DataFrame(merged)


