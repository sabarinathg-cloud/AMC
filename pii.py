def normalize_transcript_for_alignment(text, labels):
    """
    Convert transcript into the char format expected by the tutorial:
    |WORD|WORD|...
    Keeps only chars موجودة in the model label set.
    """
    text = str(text).upper().strip()

    # normalize whitespace
    text = re.sub(r"\s+", " ", text)

    # convert spaces to word boundary token
    text = text.replace(" ", "|")

    # keep only chars present in labels
    allowed = set(labels)
    text = "".join(ch for ch in text if ch in allowed)

    # force leading and trailing boundary for merge_words logic
    if not text.startswith("|"):
        text = "|" + text
    if not text.endswith("|"):
        text = text + "|"

    # compress repeated boundaries
    text = re.sub(r"\|+", "|", text)

    return text


def get_trellis(emission, tokens, blank_id=0):
    num_frame = emission.size(0)
    num_tokens = len(tokens)

    trellis = torch.zeros((num_frame, num_tokens))
    trellis[1:, 0] = torch.cumsum(emission[1:, blank_id], 0)
    trellis[0, 1:] = -float("inf")
    trellis[-num_tokens + 1 :, 0] = float("inf")

    for t in range(num_frame - 1):
        trellis[t + 1, 1:] = torch.maximum(
            trellis[t, 1:] + emission[t, blank_id],   # stay
            trellis[t, :-1] + emission[t, tokens[1:]] # change
        )
    return trellis


@dataclass
class Point:
    token_index: int
    time_index: int
    score: float


def backtrack(trellis, emission, tokens, blank_id=0):
    t, j = trellis.size(0) - 1, trellis.size(1) - 1

    path = [Point(j, t, emission[t, blank_id].exp().item())]
    while j > 0:
        assert t > 0

        p_stay = emission[t - 1, blank_id]
        p_change = emission[t - 1, tokens[j]]

        stayed = trellis[t - 1, j] + p_stay
        changed = trellis[t - 1, j - 1] + p_change

        t -= 1
        if changed > stayed:
            j -= 1

        prob = (p_change if changed > stayed else p_stay).exp().item()
        path.append(Point(j, t, prob))

    while t > 0:
        prob = emission[t - 1, blank_id].exp().item()
        path.append(Point(j, t - 1, prob))
        t -= 1

    return path[::-1]


@dataclass
class Segment:
    label: str
    start: int
    end: int
    score: float

    @property
    def length(self):
        return self.end - self.start


def merge_repeats(path, transcript):
    i1, i2 = 0, 0
    segments = []

    while i1 < len(path):
        while i2 < len(path) and path[i1].token_index == path[i2].token_index:
            i2 += 1

        score = sum(path[k].score for k in range(i1, i2)) / (i2 - i1)
        segments.append(
            Segment(
                transcript[path[i1].token_index],
                path[i1].time_index,
                path[i2 - 1].time_index + 1,
                score,
            )
        )
        i1 = i2

    return segments


def merge_words(segments, separator="|"):
    words = []
    i1, i2 = 0, 0

    while i1 < len(segments):
        if i2 >= len(segments) or segments[i2].label == separator:
            if i1 != i2:
                segs = segments[i1:i2]
                word = "".join(seg.label for seg in segs)
                score = sum(seg.score * seg.length for seg in segs) / sum(seg.length for seg in segs)
                words.append(
                    Segment(
                        word,
                        segments[i1].start,
                        segments[i2 - 1].end,
                        score,
                    )
                )
            i1 = i2 + 1
            i2 = i1
        else:
            i2 += 1

    return words


def align_from_df_index_torchaudio(
    idx,
    df,
    final_col="final_transcript.1",
    audio_template="/mnt/amc-data/pipeline/audio/sampled_channels/{id}/{channel}.wav",
):
    row = df.iloc[idx]

    transcript_raw = str(row[final_col]).strip()
    transcript = normalize_transcript_for_alignment(transcript_raw, labels)

    audio_path = audio_template.format(id=row["id"], channel=row["channel"])

    print("ROW INDEX:", idx)
    print("ROW ID:", row["id"])
    print("CHANNEL:", row["channel"])
    print("AUDIO PATH:", audio_path)
    print("\nFINAL TRANSCRIPT:\n")
    print(transcript_raw)
    print("\nALIGNMENT TRANSCRIPT:\n")
    print(transcript)

    display(Audio(filename=audio_path))

    waveform, sr = torchaudio.load(audio_path)

    # convert to mono if needed
    if waveform.size(0) > 1:
        waveform = waveform.mean(dim=0, keepdim=True)

    # resample if needed
    if sr != bundle.sample_rate:
        waveform = torchaudio.functional.resample(waveform, sr, bundle.sample_rate)
        sr = bundle.sample_rate

    with torch.inference_mode():
        emissions, _ = model(waveform.to(device))
        emissions = torch.log_softmax(emissions, dim=-1)

    emission = emissions[0].cpu().detach()

    tokens = [dictionary[c] for c in transcript]
    trellis = get_trellis(emission, tokens, blank_id=BLANK_ID)
    path = backtrack(trellis, emission, tokens, blank_id=BLANK_ID)
    segments = merge_repeats(path, transcript)
    word_segments = merge_words(segments)

    # map frame positions to seconds
    ratio = waveform.size(1) / trellis.size(0)

    rows = []
    for seg in word_segments:
        start_sample = int(ratio * seg.start)
        end_sample = int(ratio * seg.end)

        rows.append({
            "word": seg.label,
            "start": start_sample / sr,
            "end": end_sample / sr,
            "duration": (end_sample - start_sample) / sr,
            "score": seg.score,
        })

    word_df = pd.DataFrame(rows)
    display(word_df)

    return {
        "row": row,
        "audio_path": audio_path,
        "transcript_raw": transcript_raw,
        "transcript_aligned": transcript,
        "word_timestamps": word_df,
        "segments": word_segments,
        "waveform": waveform,
        "sample_rate": sr,
    }

