def get_idx_from_callid_channel(df, call_id, channel):
    match = df[
        (df["id"].astype(str) == str(call_id)) &
        (df["channel"].astype(str) == str(channel))
    ]

    if match.empty:
        raise ValueError(f"No row found for id={call_id}, channel={channel}")

    if len(match) > 1:
        print("Warning: multiple matches found. Returning the first one.")

    return match.index[0]

