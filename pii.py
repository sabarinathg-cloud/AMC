def resolve_overlaps(entities):
    entities = sorted(
        entities,
        key=lambda x: (x["start"], -(x["end"] - x["start"]), -x.get("score", 0.0))
    )

    kept = []
    for ent in entities:
        has_overlap = False
        replace_idx = None

        for i, k in enumerate(kept):
            overlap = not (ent["end"] <= k["start"] or ent["start"] >= k["end"])
            if overlap:
                has_overlap = True
                if ent.get("score", 0.0) > k.get("score", 0.0):
                    replace_idx = i
                break

        if not has_overlap:
            kept.append(ent)
        elif replace_idx is not None:
            kept[replace_idx] = ent

    return sorted(kept, key=lambda x: x["start"])


def dedupe_mask_entities(entities):
    best = {}

    for e in entities:
        key = (e["start"], e["end"], str(e["text"]).strip().lower())
        cur = best.get(key)

        if cur is None:
            best[key] = e
            continue

        cur_pri = MASK_TYPE_PRIORITY.get(cur["type"], 999)
        new_pri = MASK_TYPE_PRIORITY.get(e["type"], 999)

        if new_pri < cur_pri:
            best[key] = e

    return sorted(best.values(), key=lambda x: (x["start"], x["end"]))


